import { useEffect, useState, type ChangeEvent, type FormEvent } from 'react'
import { isAxiosError } from 'axios'
import { Camera, Check, Layers, Leaf, Sprout, Upload } from 'lucide-react'

import { analyzePhoto, getCrops } from './services/api'
import type { CropItem } from './types'

type PhotoSubject = 'soil' | 'crop' | 'fertilizer'
type LocalPhoto = { file: File; url: string }

function requestError(error: unknown): string {
  if (isAxiosError<{ detail?: string }>(error)) {
    if (typeof error.response?.data?.detail === 'string') return error.response.data.detail
    if (!error.response) return 'Cannot reach the backend. Check that it is running and try again.'
    return `The photo-guide request failed (HTTP ${error.response.status}).`
  }
  return error instanceof Error ? error.message : 'The photo-guide request could not be completed.'
}

function buildGuide(crop: CropItem, subject: PhotoSubject, notes: string): string {
  const subjectNote = {
    soil: 'The soil photo is not analyzed. Use your own observations and a soil test for pH or nutrient decisions.',
    crop: 'The crop photo is not analyzed. Use your own observations to describe the growth stage or symptoms.',
    fertilizer: 'The fertilizer photo is not analyzed. Check and enter the product label yourself; do not use an unidentified product.',
  }[subject]
  const fieldNotes = notes.trim() || 'No additional field observations entered.'

  return [
    `${crop.crop_name} cultivation plan`,
    'This plan is assembled from the AgriBloom crop profile and your notes; it is not generated by image recognition.',
    '',
    '1. Choose the site and season',
    `Season: ${crop.season}. Climate: ${crop.climate}.`,
    `Check that your local planting window and water supply suit this crop.`,
    '',
    '2. Prepare the soil',
    crop.suitable_soil,
    `Soil types listed for this crop: ${crop.soil_type}.`,
    'Clear persistent weeds, provide drainage, and work the soil only when it is not waterlogged.',
    '',
    '3. Select planting material and plant',
    crop.sowing_season,
    'Use healthy, locally adapted seed or planting material. Confirm variety-specific spacing and planting depth with local extension guidance.',
    '',
    '4. Plan organic fertility',
    crop.organic_fertilizers,
    'Use mature, permitted inputs and avoid applying amendments based only on appearance.',
    '',
    '5. Manage water',
    crop.irrigation,
    '',
    '6. Monitor crop health and pests',
    crop.pest_management,
    'Inspect plants regularly, record changes, and confirm suspected disease or nutrient problems before treating.',
    '',
    '7. Harvest and store',
    crop.harvesting,
    '',
    'Photo and field notes',
    subjectNote,
    `Your notes: ${fieldNotes}`,
    '',
    'Important: This is general crop guidance. Soil, climate, variety, and local regulations affect the right practice. Verify high-impact decisions with a soil test or local agricultural adviser.',
  ].join('\n')
}

export default function PhotoGuidePage() {
  const [photo, setPhoto] = useState<LocalPhoto | null>(null)
  const [subjectType, setSubjectType] = useState<PhotoSubject>('crop')
  const [selectedCropId, setSelectedCropId] = useState('')
  const [notes, setNotes] = useState('')
  const [crops, setCrops] = useState<CropItem[]>([])
  const [guide, setGuide] = useState('')
  const [guideSource, setGuideSource] = useState('')
  const [error, setError] = useState('')
  const [loading, setLoading] = useState(true)
  const [analyzing, setAnalyzing] = useState(false)
  const [providerConsent, setProviderConsent] = useState(false)

  useEffect(() => {
    return () => {
      if (photo) URL.revokeObjectURL(photo.url)
    }
  }, [photo])

  useEffect(() => {
    let active = true
    getCrops()
      .then((items) => {
        if (!active) return
        setCrops(items)
        setSelectedCropId(String(items[0]?.id ?? ''))
      })
      .catch((loadError: unknown) => {
        if (active) setError(requestError(loadError))
      })
      .finally(() => {
        if (active) setLoading(false)
      })
    return () => {
      active = false
    }
  }, [])

  const selectedCrop = crops.find((crop) => String(crop.id) === selectedCropId)
  const notesPrompt = {
    soil: 'Describe what you observe, such as texture, drainage, or recent soil-test results.',
    crop: 'Describe the crop stage, visible symptoms, or what you have already tried.',
    fertilizer: 'Enter the product name and label directions you can read. Do not guess missing ingredients.',
  }[subjectType]

  const handleImageChange = (event: ChangeEvent<HTMLInputElement>) => {
    const selected = event.target.files?.[0] ?? null
    setGuide('')
    setGuideSource('')
    setError('')
    setProviderConsent(false)
    if (!selected) {
      setPhoto(null)
      return
    }
    if (!['image/jpeg', 'image/png'].includes(selected.type)) {
      setPhoto(null)
      setError('Choose a JPEG or PNG image.')
      event.target.value = ''
      return
    }
    if (selected.size > 10 * 1024 * 1024) {
      setPhoto(null)
      setError('The image must be no larger than 10 MB.')
      event.target.value = ''
      return
    }
    setPhoto({ file: selected, url: URL.createObjectURL(selected) })
  }

  const handleSubmit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault()
    if (!selectedCrop) {
      setError('Choose a crop profile to build its cultivation guide.')
      return
    }
    if (!photo) {
      setError('Choose a JPEG or PNG photo to analyze.')
      return
    }
    if (!providerConsent) {
      setError('Confirm that you want to send this photo and its notes to Groq for analysis.')
      return
    }
    setAnalyzing(true)
    setError('')
    setGuide('')
    setGuideSource('')
    try {
      const result = await analyzePhoto(photo.file, selectedCrop.crop_name, subjectType, notes)
      setGuide(result.answer)
      setGuideSource(`AI photo analysis · ${result.model}`)
    } catch (analysisError: unknown) {
      setError(requestError(analysisError))
    } finally {
      setAnalyzing(false)
    }
  }

  const handleProfileOnlyGuide = () => {
    if (!selectedCrop) {
      setError('Choose a crop profile to build its cultivation guide.')
      return
    }
    setError('')
    setGuide(buildGuide(selectedCrop, subjectType, notes))
    setGuideSource('Crop profile and notes only · photo not analyzed')
  }

  return (
    <section className="content-page photo-guide-page">
      <header className="photo-guide-heading">
        <div>
          <p className="eyebrow accent">AgriBloom visual guide</p>
          <h1>Start with a photo from your field.</h1>
          <p>Choose what you want help with, add a little context, and get practical guidance for your crop.</p>
        </div>
        <div className="photo-guide-steps" aria-label="How the photo guide works">
          <span className="current">01 <b>Photo</b></span>
          <span>02 <b>Subject</b></span>
          <span>03 <b>Context</b></span>
        </div>
      </header>

      <div className="photo-guide-layout">
        <form className="photo-guide-card photo-guide-form" onSubmit={handleSubmit}>
          <div className="photo-step-heading">
            <span className="photo-step-number">01</span>
            <div>
              <p className="eyebrow">Your starting point</p>
              <h2>Choose a field photo</h2>
            </div>
          </div>

          <label className={`photo-upload-label ${photo ? 'has-photo' : ''}`}>
            <span className="photo-upload-content">
              <span className="photo-upload-icon"><Camera size={27} /></span>
              <strong>{photo ? 'Your photo is ready' : 'Add a photo of what you see'}</strong>
              <span className="photo-upload-hint">A clear, well-lit photo helps provide useful context.</span>
              <span className="photo-upload-control">
                <Upload size={17} />
                {photo ? 'Choose a different photo' : 'Choose photo'}
              </span>
              <span className="photo-upload-format">JPEG or PNG · up to 10 MB</span>
            </span>
            <input type="file" accept="image/jpeg,image/png" onChange={handleImageChange} />
          </label>

          {photo && <img className="photo-preview" src={photo.url} alt="Local farm photo preview" />}

          <div className="photo-subject-section">
            <div className="photo-step-heading">
              <span className="photo-step-number">02</span>
              <div>
                <p className="eyebrow">Photo subject</p>
                <h2>What does it show?</h2>
              </div>
            </div>
            <div className="photo-subject-options" role="group" aria-label="Choose what the photo shows">
              <button
                type="button"
                className={`photo-subject-option ${subjectType === 'crop' ? 'selected' : ''}`}
                aria-pressed={subjectType === 'crop'}
                onClick={() => setSubjectType('crop')}
              >
                <Sprout size={21} />
                <span><strong>Crop or plant</strong><small>Growth or symptoms</small></span>
                {subjectType === 'crop' && <Check className="photo-subject-check" size={17} />}
              </button>
              <button
                type="button"
                className={`photo-subject-option ${subjectType === 'soil' ? 'selected' : ''}`}
                aria-pressed={subjectType === 'soil'}
                onClick={() => setSubjectType('soil')}
              >
                <Layers size={21} />
                <span><strong>Soil or field</strong><small>Texture or condition</small></span>
                {subjectType === 'soil' && <Check className="photo-subject-check" size={17} />}
              </button>
              <button
                type="button"
                className={`photo-subject-option ${subjectType === 'fertilizer' ? 'selected' : ''}`}
                aria-pressed={subjectType === 'fertilizer'}
                onClick={() => setSubjectType('fertilizer')}
              >
                <Leaf size={21} />
                <span><strong>Fertilizer</strong><small>Product or compost</small></span>
                {subjectType === 'fertilizer' && <Check className="photo-subject-check" size={17} />}
              </button>
            </div>
          </div>

          <div className="photo-context-heading">
            <span className="photo-step-number">03</span>
            <div>
              <p className="eyebrow">Add useful context</p>
              <h2>Help tailor your guidance</h2>
            </div>
          </div>
          <label>
            Crop profile
            <select
              value={selectedCropId}
              onChange={(event) => {
                setSelectedCropId(event.target.value)
                setGuide('')
              }}
              disabled={loading || crops.length === 0}
              required
            >
              <option value="" disabled>{loading ? 'Loading crops…' : 'Choose a crop'}</option>
              {crops.map((crop) => <option key={crop.id} value={crop.id}>{crop.crop_name}</option>)}
            </select>
          </label>

          <label>
            Your observations or label details <span className="optional-label">(optional)</span>
            <textarea
              value={notes}
              onChange={(event) => setNotes(event.target.value)}
              maxLength={1000}
              rows={4}
              placeholder={notesPrompt}
            />
          </label>

          <p className="privacy-note">
            <strong>Photo privacy and cost:</strong> When you request analysis, the selected image, crop, and notes are sent to Groq's vision API.
            AgriBloom does not save the image. Groq may charge for model usage; check its current pricing. Do not include personal or sensitive information.
          </p>
          <label className="photo-consent">
            <input
              type="checkbox"
              checked={providerConsent}
              onChange={(event) => setProviderConsent(event.target.checked)}
            />
            <span>I agree to send this photo and its notes to Groq for analysis.</span>
          </label>
          {error && <p className="error-text" role="alert">{error}</p>}
          {loading && <p className="status-text">Loading crop profiles…</p>}
          {!loading && crops.length === 0 && !error && (
            <p className="status-text">No crop profiles are available. Add one in the Crops section first.</p>
          )}
          <button className="primary-button full-width" type="submit" disabled={loading || analyzing || !selectedCrop || !photo || !providerConsent}>
            <Camera size={17} />
            {analyzing ? 'Analyzing photo…' : 'Analyze photo with AI'}
          </button>
          <button className="secondary-button full-width" type="button" disabled={loading || !selectedCrop} onClick={handleProfileOnlyGuide}>
            Use crop profile without photo analysis
          </button>
        </form>

        <aside className="photo-guide-card photo-guide-help">
          <div className="icon-wrap"><Leaf size={20} /></div>
          <h2>Guide stages</h2>
          <ul>
            <li>Season, climate, and site selection.</li>
            <li>Soil preparation and planting.</li>
            <li>Organic fertility and irrigation.</li>
            <li>Pest monitoring through harvest and storage.</li>
          </ul>
          <p className="small-note">
            A photo alone cannot establish soil pH, nutrient levels, disease, or fertilizer contents.
            Use a soil test, read product labels, and confirm important decisions with local agricultural guidance.
          </p>
        </aside>
      </div>

      {guide && (
        <section className="photo-guide-result" aria-live="polite">
          <p className="eyebrow">{guideSource}</p>
          <div className="guide-output">{guide}</div>
          <p className="small-note">
            A photo cannot confirm a diagnosis, soil chemistry, or product contents. Verify important treatment decisions with a soil test, product label, or local agricultural expert.
          </p>
        </section>
      )}
    </section>
  )
}
